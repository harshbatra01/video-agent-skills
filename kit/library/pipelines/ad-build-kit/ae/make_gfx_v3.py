"""gfx_v3.jsx: the v2 graphics that change in v6 (+ the new EFFICIENTLY/EFFECTIVELY roll), rendered to Motion graphics\\gfx_v3.
usage: python make_gfx_v3.py [name,name,...]"""
import json, os, sys, copy
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_gfx_v2 as M

OUT = "C:/VISION/IMMUFIX/repair/ENCODED RUSHES/Motion graphics/gfx_v3/"
KEEP = ['tt_qmark', 'tt_p1', 'tt_meter', 'tt_p2', 'tt_powder', 'tt_vmn', 'tt_p3', 'q3_vmn', 'i52_vmn', 'rp_vmn']

# ---- v3 changes to the v2 specs
for kind, sp in M.SPECS:
    if sp['name'] == 'tt_meter':        # starts with the (earlier) vitamin C B-roll, not over Paula
        sp['_start'] = 10.30
    if sp['name'] == 'tt_p2':           # no "noun" line
        sp['p2']['noun'] = ''
    if sp['name'] == 'tt_powder':       # she says "Reformulated" (one word)
        sp['beats'] = [dict(kick=[], kIn=19.06, mains=[['REFORMULATED', 19.06]], out=20.00),
                       dict(kick=[['TO ENSURE', 'WHITE']], kIn=20.06, mains=[['YOUR BODY', 20.58]], out=-1)]
specs = [x for x in M.build_specs() if x[1]['name'] in KEEP]
# ---- new: "can absorb it EFFICIENTLY -> EFFECTIVELY" (3 things, over A-roll 25.27-27.60)
s0, e0 = 25.27, 27.60
eff = dict(name='tt_eff', ad='f233433f', kick=[['CAN ABSORB IT', 'WHITE']], kIn=round(25.42 - s0, 4),
           pre='EFF', midA='ICIENT', midB='ECTIVE', post='LY', t0=round(26.30 - s0, 4), tR=round(27.04 - s0, 4), dur=round(e0 - s0, 4))
specs.append(['eff', eff, s0, e0])

if __name__ == '__main__':
    only = sys.argv[1].split(',') if len(sys.argv) > 1 else []
    json.dump([[k, d] for k, d, s, e in specs], open(os.path.join(HERE, 'gfx_v3_specs.json'), 'w'), indent=0)
    meta = {d['name']: dict(kind=k, start=s, end=e, ad=d.get('ad')) for k, d, s, e in specs}
    json.dump(meta, open(os.path.join(HERE, 'gfx_v3_meta.json'), 'w'), indent=0)
    hdr = '''// Immufix motion graphics v3 (generated by make_gfx_v3.py). Run: AfterFX.exe -r gfx_v3.jsx
app.beginSuppressDialogs();
var OUT = "%s";
var IN = "%s";
var ONLY = %s;
var W = 1080, H = 1920, FPS = 60;
var WHITE = [1, 1, 1], RED = [1, 0.231, 0.188], GREEN = [0.204, 0.820, 0.482], YELLOW = [1, 0.79, 0.235], INK = [0.08, 0.08, 0.09];
var GREY = [0.77, 0.79, 0.82], HL = [1, 0.81, 0.23];
var BIG = "Coolvetica-HeavyComp", KICK = "ProximaNova-Extrabld", SEMI = "ProximaNova-Semibold", REG = "ProximaNova-Regular";
var SERIFB = "Georgia-Bold", SERIFI = "Georgia-Italic";
var MAIN_Y = 1590, KICK_Y = 1370;
var LOG = [];
function log(s) { LOG.push(s); }
function writeFile(path, s) { var f = new File(path); f.encoding = "UTF-8"; f.open("w"); f.write(s); f.close(); }
''' % (OUT, M.IN, json.dumps(only))
    helpers = open(os.path.join(HERE, 'gfx_helpers_v1.jsx'), encoding='utf-8').read()
    v1 = open(os.path.join(HERE, 'gfx_v1.jsx'), encoding='utf-8').read()
    counter_src = v1[v1.index('function counter(sp)'):v1.index('// ---------------------------------------------------------------- the batch')]
    body = open(os.path.join(HERE, 'gfx_v3_body.jsx'), encoding='utf-8').read()
    run = '''
var SPECS = %s;
var COLORS = {"WHITE": WHITE, "RED": RED, "GREEN": GREEN};
function fixColors(o) { if (o instanceof Array) { for (var i = 0; i < o.length; i++) { if (typeof o[i] == "string" && COLORS[o[i]] && i == 1) o[i] = COLORS[o[i]]; else fixColors(o[i]); } } else if (o && typeof o == "object") { for (var k in o) fixColors(o[k]); } }
try {
    var proj = app.newProject();
    var f = new Folder(OUT); if (!f.exists) f.create();
    var outs = [];
    for (var j = 0; j < SPECS.length; j++) {
        var kind = SPECS[j][0], sp = SPECS[j][1], c = null;
        var want = !ONLY.length; for (var q = 0; q < ONLY.length; q++) if (ONLY[q] == sp.name) want = true;
        if (!want) continue;
        fixColors(sp);
        try {
            if (kind == "cap") c = caption2(sp);
            else if (kind == "stack") c = stack(sp);
            else if (kind == "glass") c = glass2(sp);
            else if (kind == "meter") c = meter2(sp);
            else if (kind == "qmark") c = qmark(sp);
            else if (kind == "eff") c = effRoll(sp);
            outs.push([sp.name, c]); log("built " + sp.name);
        } catch (e) { log("FAILED " + sp.name + ": " + e.toString() + " line " + e.line); }
        writeFile(OUT + "gfx_v3_log.txt", LOG.join("\\n"));
    }
    var gs = []; for (var gk in GEOM) { var g = GEOM[gk]; gs.push('"' + gk + '": {"x0": ' + g.x0 + ', "y0": ' + g.y0 + ', "w": ' + g.w + ', "h1": ' + g.h1 + ', "h2": ' + g.h2 + ', "r": ' + g.r + ', "tIn": ' + g.tIn + ', "tOut": ' + g.tOut + ', "tG": ' + g.tG + ', "dur": ' + g.dur + '}'); }
    if (gs.length) writeFile(OUT + "glass_geom.json", "{" + gs.join(", ") + "}");
    proj.save(new File(OUT + "immufix_gfx_v3.aep"));
    for (var o = 0; o < outs.length; o++) {
        var rq = proj.renderQueue.items.add(outs[o][1]);
        rq.outputModule(1).applyTemplate("High Quality with Alpha");
        rq.outputModule(1).file = new File(OUT + outs[o][0]);
        log("render " + outs[o][0]); writeFile(OUT + "gfx_v3_log.txt", LOG.join("\\n"));
        proj.renderQueue.render();
        rq.remove();
    }
    proj.save();
    LOG.push("render done");
} catch (err) { LOG.push("FATAL " + err.toString() + " line " + err.line); }
writeFile(OUT + "gfx_v3_log.txt", LOG.join("\\n"));
writeFile(OUT + "gfx_v3_DONE.txt", "done");
''' % json.dumps([[k, d] for k, d, s, e in specs])
    open(os.path.join(HERE, 'gfx_v3.jsx'), 'w', encoding='utf-8').write(hdr + helpers + '\n' + counter_src + '\n' + body + run)
    print('wrote gfx_v3.jsx with', len(specs), 'specs:', ', '.join('%s %.2f-%.2f' % (d['name'], s, e) for k, d, s, e in specs))
